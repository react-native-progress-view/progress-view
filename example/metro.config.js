const path = require('path');
const pack = require('../package.json');

// The library is linked from the repository root (`link:../` in package.json).
// Metro in RN 0.68 doesn't follow symlinks, so resolve the library and its peer
// dependencies explicitly, and keep the root's own copies of the peers out of
// the bundle so only the example's react/react-native are used.
const root = path.resolve(__dirname, '..');
const peers = Object.keys(pack.peerDependencies);

// Forward slashes, regex-escaped; exclusionList maps `/` to the platform separator.
const toPattern = (p) =>
  p.replace(/\\/g, '/').replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const exclusionList = (() => {
  try {
    return require('metro-config/src/defaults/exclusionList');
  } catch (_) {
    // `blacklist` was renamed to `exclusionList` in 0.60
    return require('metro-config/src/defaults/blacklist');
  }
})();

const blockList = exclusionList([
  /node_modules\/.*\/node_modules\/react-native\/.*/,

  // This stops "react-native run-windows" from causing the metro server to
  // crash if its already running
  new RegExp(`${path.join(__dirname, 'windows').replace(/[/\\]+/g, '/')}.*`),

  // Workaround for `EPERM: operation not permitted, lstat '~\midl-MIDLRT-cl.read.1.tlog'`
  /.*\.tlog/,

  // Prevent Metro from watching temporary files generated by Visual Studio
  // otherwise it may crash when they are removed when closing a project.
  /.*\/.vs\/.*/,

  // Workaround for `EBUSY: resource busy or locked, open '~\msbuild.ProjectImports.zip'`
  /.*\.ProjectImports\.zip/,

  ...peers.map(
    (m) => new RegExp(`^${toPattern(path.join(root, 'node_modules', m))}/.*$`),
  ),
]);

module.exports = {
  projectRoot: __dirname,
  watchFolders: [root],
  resolver: {
    blacklistRE: blockList,
    blockList,
    extraNodeModules: peers.reduce(
      (acc, name) => {
        acc[name] = path.join(__dirname, 'node_modules', name);
        return acc;
      },
      {[pack.name]: root},
    ),
  },
  transformer: {
    getTransformOptions: async () => ({
      transform: {
        experimentalImportSupport: false,
        inlineRequires: false,
      },
    }),
  },
};
